#pragma once

// Educational Host-only policy. Not part of CoreRPG's public API, authentication,
// transport, parser, or a general authorization system.
#include <corerpg/action.hpp>
#include <corerpg/context_builder.hpp>
#include <corerpg/random_streams.hpp>
#include <corerpg/world_state.hpp>

#include <optional>

namespace example_host {
struct AuthenticatedSession {
    corerpg::EntityId actor;
    std::uint64_t epoch{}; // Host changes on restore/replacement/revocation.
    bool placement_allowed{}; // Recomputed domain permission, never model input.
};
struct IssuedContext {
    std::uint64_t id{}; // Opaque correlation ID, not a world revision.
    std::uint64_t epoch{};
    corerpg::EntityId actor;
    std::uint64_t revision{}; // Private server-side binding, never in model context.
};
/// Decoder must already reject unknown fields/operations, oversized data and
/// invalid numeric representations. This finite DTO supports only placement.
struct PlacementProposal {
    std::uint64_t context_id{};
    corerpg::EntityId entity;
    corerpg::EntityId container;
};
enum class Status { denied, evaluated };
struct Result {
    Status status{Status::denied};
    std::optional<corerpg::ActionResult> technical; // Privileged! Not provider output.
};

/// Single-threaded illustrative policy: actor may place itself in a currently
/// authorized container, only with a current server-issued context/session.
/// current_view is regenerated by the trusted Host, never supplied by the model.
/// Production must also enforce expiration, authenticated transport, one-time
/// proposal IDs/deduplication and all game-specific constraints before execution.
inline Result evaluate(corerpg::WorldState& world, corerpg::RandomStreams& random,
                       const AuthenticatedSession& session, const IssuedContext& issued,
                       const corerpg::ObserverView& current_view, const PlacementProposal& proposal) {
    if (!session.placement_allowed || issued.epoch != session.epoch ||
        issued.actor != session.actor || issued.id != proposal.context_id ||
        proposal.entity != session.actor || !current_view.knows(proposal.entity) ||
        !current_view.knows(proposal.container)) return {};
    const corerpg::ActionRequest request{session.actor,
        corerpg::PlaceEntityAction{proposal.entity, proposal.container}, issued.revision};
    return {Status::evaluated, corerpg::ActionEngine::process(world, random, request)};
}
} // namespace example_host
